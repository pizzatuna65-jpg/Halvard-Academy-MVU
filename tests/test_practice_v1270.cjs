const fs = require('fs'), path = require('path');
const { initState, applyPatch, ok, ROOT } = require('./harness.cjs');
const E = new Function(fs.readFileSync(path.join(ROOT, 'src/scripts/engine.js'), 'utf8') + '\nreturn { fromAbs };')();
const at = (S, d, time, loc, extra = []) => { const T = E.fromAbs(d * 1440 + (+time.slice(0,2))*60 + (+time.slice(3)));
  return applyPatch(S, [...['Year','Month','Week','Day','Time'].map(k => ({ op:'replace', path:'/World/'+k, value:T[k] })), { op:'replace', path:'/World/Location', value:loc }, ...extra]); };
const report = (S, d, time, loc, Action, Subject = '', With = '') => at(S,d,time,loc,[{ op:'insert', path:'/Practice/-', value:{Action,Subject,With} }]);
const S0 = at(initState(), 0, '16:00', 'Main Library');
const good = report(S0,0,'17:00','Main Library','Study a subject','History');
ok(good.$eng.prof.xp.Knowledge >= 1 && good.Practice.length === 0, 'a real study session awards XP and clears the report');
const short = report(S0,0,'16:30','Main Library','Study a subject','History');
ok(short.$eng.prof.xp.Knowledge === S0.$eng.prof.xp.Knowledge && short._Log.some(x => x.includes('45 minutes')), 'a short session is rejected');
const moved = report(S0,0,'17:00','Archive','Dig through the records');
ok(moved._Log.some(x => x.includes('start and finish')), 'moving into a place during the report is rejected');
const wrong = report(S0,0,'17:00','Main Library','Drill');
ok(wrong._Log.some(x => x.includes('not available here')), 'an action at the wrong place is rejected');
const again = report(good,0,'18:00','Main Library','Study a subject','History');
ok(again._Log.some(x => x.includes('already practised')), 'same action cannot be repeated the same day');
const classTime = report(at(initState(),1,'08:00','Main Library'),1,'09:00','Main Library','Study a subject','History');
ok(classTime._Log.some(x => x.includes('during a lesson')), 'practice cannot overlap a class');
const noPartner = report(at(initState(),0,'16:00','Study Rooms'),0,'17:00','Study Rooms','Group study','History');
ok(noPartner._Log.some(x => x.includes('partner')), 'group study needs a present partner');
const enough = good.$ui.practice.some(a => a.action === 'Study a subject');
ok(enough, 'the engine lists practice available here for <now> and the UI');
const hall = at(initState(),0,'16:00','Potion Halls');
const capped = JSON.parse(JSON.stringify(hall)); capped.$eng.prof.wk.Craft = 6;
const blocked = report(capped,0,'17:00','Potion Halls','Reagent drill');
ok(blocked._Log.some(x => x.includes('weekly limit')) && blocked.$eng.prof.xp.Craft === capped.$eng.prof.xp.Craft, 'weekly stat cap blocks repeatable XP');
const slow = applyPatch(hall,[{op:'replace',path:'/$ui/tune',value:{prof_pace:4}}]);
ok(slow.$eng.prof.wk.w === hall.$eng.prof.wk.w, 'pace setting keeps the current weekly ledger');
const group0 = at(initState(),0,'16:00','Study Rooms', [{op:'replace',path:'/Scene/Present',value:{Irene:{Note:'ready to study'}}}]);
const group = report(group0,0,'17:00','Study Rooms','Group study','History','Irene');
ok(group.$eng.prof.xp.Knowledge >= 2 && !group._Log.some(x => x.includes('a partner present')), 'group study succeeds with a present partner');
const club0 = at(initState(),0,'16:00','Club Rooms');
const club = report(club0,0,'17:00','Club Rooms','Specialized Magic practice');
ok(club._Log.some(x => x.includes('Specialized Magic Club')), 'club-only action needs membership');
const gym0 = at(initState(),0,'16:00','Gymnasium');
const gym = report(gym0,0,'17:00','Gymnasium','Train');
ok(gym.Player.$Training.stamina.gain > gym0.Player.$Training.stamina.gain && gym.$eng.prof.xp.Prowess >= 1, 'physical practice is an ordinary stamina training session');
const forage0 = at(initState(),84,'16:00','Forest');
const forage = report(forage0,84,'17:00','Forest','Forage');
ok(forage._Log.some(x => x.includes('Spring or Autumn only')), 'foraging respects the season');
global.window = { parent: { document: {} } };
const U = new Function(fs.readFileSync(path.join(ROOT, 'src/scripts/ui.js'), 'utf8') + '\nreturn { PANELS, view, renderProfile };')();
U.view.act = 'practice';
const panel = U.PANELS.activities.render(good);
ok(/data-actab="practice"/.test(panel) && /Here/.test(panel) && /Study a subject/.test(panel) && /Elsewhere/.test(panel), 'Activities renders the unlocked Practice tab and local action');
U.view.tab = 'studies';
const studies = U.renderProfile(good);
ok(/<svg[^>]+aria-label="Six proficiency ranks/.test(studies) && /Knowledge/.test(studies) && /this week/.test(studies), 'Studies renders the six-axis chart and weekly XP');
