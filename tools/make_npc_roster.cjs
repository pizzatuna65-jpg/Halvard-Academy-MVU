// 1.32.0 — writes planning/NPC_ROSTER.md: every NPC in one file, so a brainstorm about new NPCs (for example "does character card X
// have someone Eldrasil does not?") needs this file and nothing else. Part 1 is a one-line-per-NPC table for a quick scan; Part 2 is
// each NPC's full lore as the narrator sees it (EJS rendered for the year the NPC is on campus; secrets included, marked).
// Re-run after lore or NPC changes (build_all.py --lore runs it):  node tools/make_npc_roster.cjs
const fs = require('fs'), path = require('path'), ejs = require('ejs'), _ = require('lodash');
const ROOT = path.join(__dirname, '..'), P = (...a) => path.join(ROOT, ...a);
const read = p => fs.readFileSync(P(p), 'utf8'), json = p => JSON.parse(read(p));
const npcs = json('data/npcs.json'), idx = json('src/worldbook/index.json'), ver = json('src/card/card.json').character_version;

const lore = {};
for (const e of idx) {
  const m = /^\[mvu_plot\] NPC — (\S+)/.exec(e.comment || '');
  if (m && npcs[m[1]]) lore[m[1]] = read(`src/worldbook/content/${e.uid}.txt`);
}
// the lore as the narrator reads it in the NPC's first year on campus (no Cast Sheet, nobody graduated)
const render = (id, t) => {
  const st = { World: { Year: npcs[id].arrives || 1 }, Player: { Profile: { Year: 1 } }, Campus_State: { Graduated: [] }, $ui: { cast: { full: [] } } };
  return ejs.render(t, { getvar: k => _.get({ stat_data: st }, k) }).replace(/\r/g, '').replace(/\n{2,}/g, '\n').trim();
};
const GROUPS = [['Halvard students — Year 1', n => n.group === 'Year 1'], ['Halvard students — Year 2', n => n.group === 'Year 2'],
  ['Halvard students — Year 3', n => n.group === 'Year 3'], ['Teaching staff and dorm heads', n => n.group === 'Staff'],
  ['Doves, Cathedral, Liaison and facilities', n => ['Doves', 'Cathedral', 'Facilities', 'Liaison'].includes(n.group)],
  ['Rival academy teams', n => /team$/.test(n.group)]];
const field = (t, k) => { const m = new RegExp(`^${k}: (.*)$`, 'm').exec(t); return m ? m[1].trim() : ''; };
const clip = (s, n) => (s.length > n ? s.slice(0, n).replace(/\s+\S*$/, '') + '…' : s);
const cell = s => String(s || '').replace(/\|/g, '/').replace(/\n/g, ' ');
const where = n => [n.academy !== 'Halvard' ? n.academy : '', n.dorm ? n.dorm + ' dorm' : '', n.year ? 'Year ' + n.year : '',
  n.arrives > 1 ? `arrives campaign Year ${n.arrives}` : ''].filter(Boolean).join(', ');
const race = n => [n.race, n.beast ? `(${n.beast})` : '', n.gender].filter(Boolean).join(' ');

const order = GROUPS.flatMap(([, f]) => Object.values(npcs).filter(f));
const text = Object.fromEntries(order.map(n => [n.id, render(n.id, lore[n.id] || '')]));
let md = `# NPC roster — Eldrasil / Halvard Academy (card v${ver})

Generated by \`tools/make_npc_roster.cjs\` from the card's NPC lore; do not edit by hand (re-run it after lore changes). ${order.length} NPCs.

**How to use.** To check whether a character from another card or idea is already covered, scan the table in Part 1 (role, magic,
temperament) first, then read only the Part 2 profiles of the close matches. Part 2 is each NPC's lore as the narrator reads it
(rendered for the year the NPC is on campus; \`<narrator_only>\` secrets included). Designing a new NPC also needs
\`planning/NPC_BRAINSTORM_BRIEF.md\` (bond system, gaps, formats).

**World in one paragraph.** Halvard Academy, Kingdom of Eldrasil: a magic academy with a sealed mystery under the castle (the
Crack, the breach two years ago). Races: Human, Elf, Beastkin. Four dorms by magic type: Elemental (Fire Dormitory), Mystic (Light
Dormitory), Spiritual (Viridian Dormitory), Occult (Sky Dormitory). The Doves are the crown's watchers on campus. Combat roles:
attack, defense, healing, support, control. Rival academies: Myrdath, Veyra, Ashvale (one team each at the Kingdom Competition).

## 1. Quick roster

| Name (id) | Group | Where | Race | Role / position | Magic | Temperament |
|---|---|---|---|---|---|---|
`;
for (const n of order) {
  const t = text[n.id];
  const first = x => x.split(/(?<=\.)\s/)[0].replace(/\.$/, ''), club = first(field(t, 'Club'));
  const role = [...(n.public_tags || []), first(field(t, 'Role')), club && !/^none/i.test(club) ? 'club: ' + club : '', n.team_role ? n.team_role + ' role on the team' : ''].filter(Boolean).join('; ');
  const temper = (n.impression || '') + (field(t, 'Personality') ? ': ' + clip(field(t, 'Personality'), 120) : '');
  md += `| ${cell(n.name)} (${n.id}) | ${cell(n.group)} | ${cell(where(n))} | ${cell(race(n))} | ${cell(clip(role, 110))} | ${cell(clip(field(t, 'Magic'), 90))} | ${cell(temper)} |\n`;
}
md += '\n## 2. Full profiles\n';
for (const [title, f] of GROUPS) {
  md += `\n### ${title}\n`;
  for (const n of Object.values(npcs).filter(f)) {
    const body = text[n.id].replace(/^\[[^\]]+\]\n/, '');
    md += `\n#### ${n.name} (${n.id})\n*${[where(n), race(n), n.nickname ? 'called ' + n.nickname : '', n.team_role ? n.team_role + ' role' : ''].filter(Boolean).join(' · ')}*\n\n${body}\n`;
  }
}
fs.writeFileSync(P('planning/NPC_ROSTER.md'), md.replace(/\n{3,}/g, '\n\n'));
console.log(`planning/NPC_ROSTER.md: ${order.length} NPCs, ~${Math.round(md.length / 4 / 1000)}k tokens`);
